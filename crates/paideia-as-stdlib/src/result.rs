//! Rust-side `Result` idiom — Wave 0 Batch 4, v0.26 M1-004 (#1363).
//!
//! This module is the AS-side surface — the Rust host code that AML tooling
//! calls when it needs to generate a `Result<T, E>`-returning wrapper around
//! some underlying fallible operation. It is NOT the runtime `Result<T, E>`
//! sum type: that already exists as a `.pdx` declaration next door at
//! `crates/paideia-as-stdlib/pdx/result.pdx`, and it is what user `.pdx`
//! code destructures with `Ok(v)` / `Err(e)` patterns.
//!
//! # What is a "recipe" here?
//!
//! The paideia-as elaborator has a standing pattern (see e.g.
//! `design/stdlib/cpuid-record-return.md` and
//! `design/toolchain/stdlib-trait-lowering.md`) of describing a callable's
//! ABI/wrapper shape as a *recipe* the code generator consumes verbatim.
//! [`Recipe<T, E>`] is the analogous descriptor for the `Result` wrapper
//! family: it names the `Ok` and `Err` types and pins the two rows every
//! `Result`-returning wrapper carries on its signature —
//!
//! ```text
//!   fn <name>(<args>) -> Result<T, E> !{Err} @{paideia.result}
//! ```
//!
//! The effect row `!{Err}` marks the wrapper as fallible in the effect
//! system (callers must be in a compatible row to invoke it), and the
//! capability row `@{paideia.result}` gates the wrapper on the ambient
//! `paideia.result` capability so the `Err`-materialisation path can be
//! audited exactly like any other capability-mediated operation.
//!
//! Tooling that generates these wrappers (the elaborator's wrapper-emitter,
//! future LSP typed-import paths, doc extractors) reads a `Recipe<T, E>`
//! and emits the signature line + prologue/epilogue accordingly.
//!
//! # `pretty_error`
//!
//! A one-line helper that formats an `Err` value in the same visual shape
//! `paideia-as-diagnostics`'s human renderer emits for a single-line
//! diagnostic (`<severity>: <label>: <message>`). It gives ad-hoc host-side
//! callers a way to log an `E` without pulling the full diagnostic pipeline.

use core::fmt;
use core::marker::PhantomData;

/// Effect-row token every `Result`-returning wrapper carries on its
/// signature. Kept as a `&'static str` (rather than a typed enum) because
/// the elaborator's signature-emission path splices row tokens as text.
pub const EFFECT_ROW: &str = "!{Err}";

/// Capability-row token every `Result`-returning wrapper carries on its
/// signature. See module-level docs for the rationale — the row gates the
/// `Err`-materialisation path on an ambient, auditable capability.
pub const CAPABILITY_ROW: &str = "@{paideia.result}";

/// Canonical error-return recipe.
///
/// Describes the shape a `Result<T, E>`-returning wrapper takes when
/// generated by downstream tooling: the `Ok` and `Err` type names as they
/// appear in the emitted signature, plus the two frozen rows (effect and
/// capability). The two generic parameters carry no data — they exist so
/// the recipe is *typed* at the recipe-registration call-site and so the
/// same wrapper generator cannot be handed two recipes that agree textually
/// but disagree on the underlying Rust types.
///
/// Copy-cheap: two `&'static str`s (the type names) plus two more (the
/// frozen rows are const-materialised from [`EFFECT_ROW`] / [`CAPABILITY_ROW`]),
/// so a `Recipe` fits in four fat pointers and passes by value everywhere.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub struct Recipe<T, E> {
    /// Type name for the `Ok` payload as it should appear inside
    /// `Result<..., ...>` in the emitted signature. Free-form string so the
    /// recipe can name a generic parameter (`"T"`), a concrete type
    /// (`"u64"`), or a fully-qualified path (`"foo::Bar"`) — whichever the
    /// caller's emission site expects.
    pub ok_type_name: &'static str,
    /// Type name for the `Err` payload, same rules as [`Recipe::ok_type_name`].
    pub err_type_name: &'static str,
    /// Effect row token — always [`EFFECT_ROW`]. Kept as a field (not
    /// re-derived) so a debug-printed recipe carries the row inline and so
    /// downstream tests can equality-check the full recipe in one call.
    pub effect_row: &'static str,
    /// Capability row token — always [`CAPABILITY_ROW`]. Same rationale as
    /// [`Recipe::effect_row`].
    pub capability_row: &'static str,
    /// PhantomData witnessing the `T, E` type parameters. `fn() -> (T, E)`
    /// is the variance-neutral, `Send`/`Sync`-preserving choice: `Recipe`
    /// never owns or produces a `T` or `E` at runtime, and we do not want
    /// the phantom to constrain `Send`/`Sync` of the recipe itself.
    _marker: PhantomData<fn() -> (T, E)>,
}

impl<T, E> Recipe<T, E> {
    /// Construct a recipe. `const` so recipe tables can be materialised at
    /// compile time — the rows are always the module-level constants.
    pub const fn new(ok_type_name: &'static str, err_type_name: &'static str) -> Self {
        Self {
            ok_type_name,
            err_type_name,
            effect_row: EFFECT_ROW,
            capability_row: CAPABILITY_ROW,
            _marker: PhantomData,
        }
    }

    /// Emit the functor signature fragment a wrapper generator splices into
    /// a function declaration:
    ///
    /// ```text
    ///   -> Result<<ok>, <err>> !{Err} @{paideia.result}
    /// ```
    ///
    /// The leading `->` is included so the caller can concatenate the
    /// argument list and this fragment without additional glue. No trailing
    /// whitespace or newline is added — the caller controls placement.
    pub fn functor_signature(&self) -> String {
        format!(
            "-> Result<{}, {}> {} {}",
            self.ok_type_name, self.err_type_name, self.effect_row, self.capability_row
        )
    }
}

/// Format an error value in the paideia-as diagnostic single-line style.
///
/// Shape: `error: <label>: <err>`. `<label>` is a short caller-supplied
/// tag naming the site (e.g. `"parse_pdx"`, `"lower"`); `<err>` is the
/// `Display` projection of the error itself. Chosen to line up visually
/// with the header line `paideia_as_diagnostics::render_human::render`
/// emits for a `severity: brief` diagnostic — an ad-hoc host-side caller
/// gets the same silhouette without pulling in the full pipeline.
///
/// Returns an owned `String` so the caller can log or forward it freely;
/// the caller pays exactly one allocation.
pub fn pretty_error<E: fmt::Display>(label: &str, err: &E) -> String {
    format!("error: {}: {}", label, err)
}

#[cfg(test)]
mod tests {
    use super::*;

    // ---------- Recipe field access ----------

    #[test]
    fn recipe_new_populates_all_fields() {
        let r: Recipe<u64, &'static str> = Recipe::new("u64", "&'static str");
        assert_eq!(r.ok_type_name, "u64");
        assert_eq!(r.err_type_name, "&'static str");
        assert_eq!(r.effect_row, "!{Err}");
        assert_eq!(r.capability_row, "@{paideia.result}");
    }

    #[test]
    fn recipe_rows_are_the_module_constants() {
        // The frozen rows are re-exported as consts; a recipe must always
        // match them so downstream tooling can compare with either.
        let r: Recipe<u64, u64> = Recipe::new("u64", "u64");
        assert_eq!(r.effect_row, EFFECT_ROW);
        assert_eq!(r.capability_row, CAPABILITY_ROW);
    }

    #[test]
    fn recipe_new_is_const_evaluable() {
        // If this compiles, `Recipe::new` stays usable in const contexts —
        // that's a load-bearing property for compile-time recipe tables.
        const R: Recipe<u64, u64> = Recipe::new("T", "E");
        assert_eq!(R.ok_type_name, "T");
        assert_eq!(R.err_type_name, "E");
    }

    #[test]
    fn recipe_functor_signature_matches_canonical_shape() {
        let r: Recipe<u64, u64> = Recipe::new("u64", "ParseErr");
        assert_eq!(
            r.functor_signature(),
            "-> Result<u64, ParseErr> !{Err} @{paideia.result}"
        );
    }

    #[test]
    fn recipe_functor_signature_accepts_generic_parameter_names() {
        // Downstream tooling that hasn't monomorphized yet may name generic
        // parameters directly; the recipe must forward the text verbatim.
        let r: Recipe<(), ()> = Recipe::new("T", "E");
        assert_eq!(
            r.functor_signature(),
            "-> Result<T, E> !{Err} @{paideia.result}"
        );
    }

    #[test]
    fn recipe_functor_signature_accepts_fully_qualified_paths() {
        // The recipe must not munge type-name text — a fully qualified
        // path (`::` and generics inside) has to round-trip untouched.
        let r: Recipe<(), ()> = Recipe::new("foo::Bar<u64>", "foo::Err");
        assert_eq!(
            r.functor_signature(),
            "-> Result<foo::Bar<u64>, foo::Err> !{Err} @{paideia.result}"
        );
    }

    #[test]
    fn recipe_is_copy_and_equatable() {
        // Recipe is a value type — copies must compare structurally.
        let r1: Recipe<u64, u64> = Recipe::new("u64", "u64");
        let r2 = r1;
        assert_eq!(r1, r2);
    }

    #[test]
    fn recipes_with_different_type_names_are_distinct() {
        let a: Recipe<u64, u64> = Recipe::new("u64", "u64");
        let b: Recipe<u64, u64> = Recipe::new("u64", "i64");
        assert_ne!(a, b);
    }

    // ---------- pretty_error against synthetic E = &'static str ----------

    #[test]
    fn pretty_error_formats_static_str_error() {
        let e: &'static str = "cap not held";
        let rendered = pretty_error("cap_check", &e);
        assert_eq!(rendered, "error: cap_check: cap not held");
    }

    #[test]
    fn pretty_error_carries_empty_label() {
        // An empty label is legal; the two colons still delimit slots so
        // downstream log-parsers can split on `": "` unambiguously.
        let e: &'static str = "boom";
        assert_eq!(pretty_error("", &e), "error: : boom");
    }

    #[test]
    fn pretty_error_carries_empty_error_body() {
        // Symmetric case — empty error text still keeps the shape.
        let e: &'static str = "";
        assert_eq!(pretty_error("site", &e), "error: site: ");
    }

    #[test]
    fn pretty_error_preserves_interior_whitespace_and_punctuation() {
        // We forward the Display projection verbatim — no trimming, no
        // escaping. Downstream renderers own presentation.
        let e: &'static str = "  two  spaces, and: colons ";
        assert_eq!(
            pretty_error("lex", &e),
            "error: lex:   two  spaces, and: colons "
        );
    }

    #[test]
    fn pretty_error_works_across_display_impls() {
        // Non-str Display types must also thread through unchanged — this
        // is the property that lets `pretty_error` be used with any `E`.
        let n: u64 = 42;
        assert_eq!(pretty_error("count", &n), "error: count: 42");
    }

    #[test]
    fn pretty_error_returns_owned_string() {
        // Compile-time witness: the result outlives the borrowed error.
        let owned: String = {
            let e: &'static str = "transient";
            pretty_error("site", &e)
        };
        assert_eq!(owned, "error: site: transient");
    }
}
