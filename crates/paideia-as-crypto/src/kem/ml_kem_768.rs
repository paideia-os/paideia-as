    /// decapsulates to SOMETHING that is not the original shared
    /// secret. The wrapper MUST NOT error out on this path — the
    /// implicit-rejection secret `z` inside `dk` produces a
    /// deterministic pseudo-random fallback instead. This test
    /// pins that: decaps still returns `Ok(_)` and the returned
    /// bytes differ from the sender's `ss` (with overwhelming
    /// probability — the fallback is a SHAKE hash so a collision
    /// is cryptographically negligible).
    #[test]
    fn tampered_ciphertext_returns_implicit_rejection_fallback() {
        let d = [0x77u8; SEED_LEN];
        let z = [0x88u8; SEED_LEN];
        let m = [0x99u8; SEED_LEN];

        let (ek, dk) = MlKem768::keygen(&d, &z).unwrap();
        let (mut ct, ss_send) = MlKem768::encaps(&ek, &m).unwrap();
        // Flip the low bit of the first ciphertext byte.
        ct[0] ^= 0x01;

        let ss_recv = MlKem768::decaps(&dk, &ct).expect(
            "decaps MUST NOT error on tampered ciphertext — implicit rejection returns a pseudo-random fallback",
        );
        assert_ne!(
            ss_recv, ss_send,
            "tampered ciphertext must not recover the sender's shared secret"
        );
    }
