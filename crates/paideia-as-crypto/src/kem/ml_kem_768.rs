    use super::*;

    /// FIPS 203 §7.1 KeyGen reproduces the NIST ACVP tcId-26 vector
    /// byte-for-byte. This is the acceptance-critical test for the
    /// deterministic path: any drift in the SHAKE-driven expansion,
    /// the CBD sampler, the NTT twiddle table, or the byte encoding
    /// would perturb ek/dk. Both keys are compared as full byte
    /// arrays.
    #[test]
    fn acvp_keygen_768_tc26_matches_vector() {
        let (ek, dk) = MlKem768::keygen(&ACVP_KG_D, &ACVP_KG_Z).expect("keygen must succeed");
        assert_eq!(
            ek, ACVP_KG_EK,
            "ML-KEM-768 KeyGen ek must match NIST ACVP tcId 26"
        );
        assert_eq!(
            dk, ACVP_KG_DK,
            "ML-KEM-768 KeyGen dk must match NIST ACVP tcId 26"
        );
    }

    /// FIPS 203 §6.2 Encaps reproduces the NIST ACVP tcId-26 vector
    /// byte-for-byte given the vector's (ek, m).
    #[test]
    fn acvp_encaps_768_tc26_matches_vector() {
        let (c, k) = MlKem768::encaps(&ACVP_EN_EK, &ACVP_EN_M).expect("encaps must succeed");
        assert_eq!(
            c, ACVP_EN_C,
            "ML-KEM-768 Encaps ciphertext must match NIST ACVP tcId 26"
        );
        assert_eq!(
            k, ACVP_EN_K,
            "ML-KEM-768 Encaps shared secret must match NIST ACVP tcId 26"
        );
    }

    /// FIPS 203 §6.3 Decaps reproduces the NIST ACVP tcId-88 "no
    /// modification" vector byte-for-byte given the vector's
    /// (dk, c). "no modification" means the ciphertext is not
    /// tampered, so the returned k is the genuine shared secret
    /// rather than an implicit-rejection fallback — this pins the
    /// non-rejection code path.
    #[test]
    fn acvp_decaps_768_tc88_matches_vector() {
        let k = MlKem768::decaps(&ACVP_DE_DK, &ACVP_DE_C).expect("decaps must succeed");
        assert_eq!(
            k, ACVP_DE_K,
            "ML-KEM-768 Decaps shared secret must match NIST ACVP tcId 88 (no modification)"
        );
    }

    /// End-to-end round-trip on a synthetic seed set: KeyGen ->
    /// Encaps -> Decaps must recover the encapsulated shared secret
    /// bit-for-bit. Pins the trait-level invariant that the two
    /// halves compose (the ACVP vectors above exercise each half
    /// independently against fixed inputs, not against each other).
    #[test]
    fn keygen_encaps_decaps_round_trip() {
        let d = [0x11u8; SEED_LEN];
        let z = [0x22u8; SEED_LEN];
        let m = [0x33u8; SEED_LEN];

        let (ek, dk) = MlKem768::keygen(&d, &z).expect("keygen");
        let (ct, ss_send) = MlKem768::encaps(&ek, &m).expect("encaps");
        let ss_recv = MlKem768::decaps(&dk, &ct).expect("decaps");

        assert_eq!(
            ss_send, ss_recv,
            "encapsulated shared secret must round-trip through decaps"
        );
    }

    /// Determinism under fixed seeds — a repeated KeyGen /
    /// Encaps under the same inputs MUST yield byte-identical
    /// output. Any accidental use of a stateful RNG inside the
    /// wrapper would fail here.
    #[test]
    fn keygen_and_encaps_are_deterministic_under_fixed_seeds() {
        let d = [0x44u8; SEED_LEN];
        let z = [0x55u8; SEED_LEN];
        let m = [0x66u8; SEED_LEN];

        let (ek_a, dk_a) = MlKem768::keygen(&d, &z).unwrap();
        let (ek_b, dk_b) = MlKem768::keygen(&d, &z).unwrap();
        assert_eq!(ek_a, ek_b, "KeyGen must be deterministic in ek");
        assert_eq!(dk_a, dk_b, "KeyGen must be deterministic in dk");

        let (ct_a, ss_a) = MlKem768::encaps(&ek_a, &m).unwrap();
        let (ct_b, ss_b) = MlKem768::encaps(&ek_a, &m).unwrap();
        assert_eq!(ct_a, ct_b, "Encaps must be deterministic in ct");
        assert_eq!(ss_a, ss_b, "Encaps must be deterministic in ss");
    }

