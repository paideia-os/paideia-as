/// Discover the PaideiaOS repo: `PAIDEIA_OS_PATH` env, else walk ancestors
/// of the crate looking for a `src/kernel/boot/kernel_main.pdx` marker.
/// Panics if not found.
///
/// #1127: when paideia-as is embedded as a submodule (canonical layout), the
/// parent paideia-os repo sits at ancestors[3..5] depending on nesting.
/// Instead of hardcoding a relative depth, probe each ancestor for the
/// kernel-main marker file.
fn find_paideia_os() -> PathBuf {
    if let Ok(path) = std::env::var("PAIDEIA_OS_PATH") {
        let p = PathBuf::from(path);
        if p.join("src/kernel/boot/kernel_main.pdx").exists() {
            return p;
        }
    }
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut ancestors_checked = Vec::new();
    for ancestor in manifest.ancestors() {
        ancestors_checked.push(ancestor.display().to_string());
        if ancestor.join("src/kernel/boot/kernel_main.pdx").exists() {
            return ancestor.to_path_buf();
        }
    }
    panic!(
        "PaideiaOS not found: set env var PAIDEIA_OS_PATH or ensure \
         src/kernel/boot/kernel_main.pdx exists in an ancestor of {}. \
         Ancestors checked: {}",
        manifest.display(),
        ancestors_checked.join(" -> ")
    );
}

/// Locate the release `paideia-as` binary built into the workspace target dir.
/// Panics if not found.
fn find_paideia_as() -> PathBuf {
    let p = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .map(|p| p.join("target/release/paideia-as"))
        .unwrap_or_else(|| PathBuf::from("target/release/paideia-as"));

    if p.exists() {
        p
    } else {
        panic!(
            "target/release/paideia-as not built; run 'cargo build --release -p paideia-as' first"
        );
    }
}

/// Build `src` to an elf64 object at `out`; return (success, stderr).
fn build(paideia_as: &Path, src: &Path, out: &Path) -> (bool, String) {
    let _ = std::fs::remove_file(out);
    let result = Command::new(paideia_as)
        .args(["build", "--emit", "elf64"])
        .arg(src)
        .args(["-o"])
        .arg(out)
        .output()
        .expect("run paideia-as");
    let ok = result.status.code() == Some(0) && out.exists();
    (ok, String::from_utf8_lossy(&result.stderr).into_owned())
}

/// Extract the `.text` section bytes from an ELF object on disk.
fn read_text_section(obj_path: &Path) -> Option<Vec<u8>> {
    let bytes = std::fs::read(obj_path).ok()?;
    let file = object::File::parse(bytes.as_slice()).ok()?;
    let text = file.section_by_name(".text")?;
    Some(text.data().ok()?.to_vec())
}

/// Render a byte slice as a compact hex string for diff messages.
fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{:02x}", b));
    }
    s
}

/// First differing offset between two slices, if any.
fn first_diff(a: &[u8], b: &[u8]) -> Option<usize> {
    let n = a.len().min(b.len());
    for i in 0..n {
        if a[i] != b[i] {
            return Some(i);
        }
    }
    if a.len() != b.len() { Some(n) } else { None }
}

/// Build all four files and assert each `.text` matches its baseline.
///
/// One test covering all four cases: it reports a full per-file byte-diff
/// summary before failing, so an encoder regression is diagnosable from the
/// test output alone.
// Re-enabled by #1127: three fixtures live-gated; pt_walk fixture restored by
// T0521 fix (#1176, commit 9758269).
#[test]
fn paideia_os_m3_four_file_text_byte_snapshot() {
    let paideia_os = find_paideia_os();
    let paideia_as = find_paideia_as();

    let kernel_dir = paideia_os.join("src/kernel");
    assert!(
        kernel_dir.exists(),
        "kernel dir missing at {:?}",
        kernel_dir
    );

    let tmpdir = std::env::temp_dir();
    let mut failures: Vec<String> = Vec::new();

    for case in CASES {
        let src = kernel_dir.join(case.rel_path);
        if !src.exists() {
            failures.push(format!(
                "{}: source missing at {}",
                case.name,
                src.display()
            ));
            continue;
        }
        let out = tmpdir.join(format!("pa8-m3-829-{}.o", case.name));

        let (ok, stderr) = build(&paideia_as, &src, &out);
        if !ok {
            failures.push(format!("{}: build failed: {}", case.name, stderr.trim()));
            continue;
        }

        let actual = match read_text_section(&out) {
            Some(t) => t,
            None => {
                failures.push(format!("{}: could not read .text section", case.name));
                continue;
            }
        };

        if actual.as_slice() == case.text {
            println!(
                "{}: .text byte-identical to baseline ({} bytes)",
                case.name,
                actual.len()
            );
        } else {
            let off = first_diff(&actual, case.text);
            failures.push(format!(
                "{}: .text MISMATCH (expected {} bytes, got {} bytes, first diff at offset {:?})\n  \
                 expected: {}\n  actual:   {}\n  \
                 If this change is EXPECTED (a deliberate encoder narrowing/mnemonic fix), \
                 update the baseline in this file and document the byte change in the commit.",
                case.name,
                case.text.len(),
                actual.len(),
                off,
                hex(case.text),
                hex(&actual),
            ));
        }
    }

    assert!(
        failures.is_empty(),
        "m3 `.text` byte-snapshot gate failed for {} file(s):\n{}",
        failures.len(),
        failures.join("\n")
    );

    println!(
        "PA8 m3-829: all 4 PaideiaOS files .text byte-identical to baseline",
    );
}
