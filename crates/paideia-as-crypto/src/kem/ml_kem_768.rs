//! ML-KEM-768 KEM — FIPS 203 (Module-Lattice-based Key-Encapsulation
//! Mechanism), NIST security-category 3 parameter set.
//!
//! # Reference
//!
//! [FIPS 203] *Module-Lattice-Based Key-Encapsulation Mechanism
//! Standard*, NIST, August 2024. Parameter set ML-KEM-768: `k = 3`,
//! `η₁ = η₂ = 2`, `du = 10`, `dv = 4`. Sizes:
//!
//! | Byte string           | Length (bytes) |
//! |-----------------------|----------------|
//! | KeyGen seed `d`       | 32             |
//! | KeyGen seed `z`       | 32             |
//! | Encaps randomness `m` | 32             |
//! | Encapsulation key `ek`| 1184           |
//! | Decapsulation key `dk`| 2400           |
//! | Ciphertext `c`        | 1088           |
//! | Shared secret `K`     | 32             |
//!
//! [FIPS 203]: https://csrc.nist.gov/pubs/fips/203/final
//!
//! # Backend
//!
//! The three primitives (`keygen`, `encaps`, `decaps`) are thin
//! wrappers over the RustCrypto [`ml-kem`] crate, running with the
//! `deterministic` feature so seed-driven KeyGen and Encaps reproduce
//! byte-identically against NIST ACVP known-answer vectors. That
//! choice mirrors the pattern already established by `Argon2id`
//! (`argon2` crate) and `ChaCha20Poly1305` (`chacha20poly1305` crate)
//! in this same tree — see `design/toolchain/rust-dep-gap-analysis.md`
//! for the "phase 1: FFI over a well-audited Rust crate, phase 6+:
//! paideia-native rewrite behind the same trait" rationale.
//!
//! [`ml-kem`]: https://docs.rs/ml-kem
//!
//! # Determinism
//!
//! FIPS 203 §7.1 (K-PKE.KeyGen) and §6.1 (ML-KEM.Encaps) both take a
//! random-tape input. This wrapper surfaces the seeds as fixed-size
//! `&[u8; 32]` parameters and threads them straight into the
//! `generate_deterministic` / `encapsulate_deterministic` entry
//! points on the underlying crate. Consequence: given the same
//! `(d, z, m)`, the wrapper produces byte-identical `(ek, dk, c, K)`
//! across processes and CPUs. Callers sample fresh seeds via the
//! `rng` module.
//!
//! # Implicit rejection (FIPS 203 §6.3)
//!
//! ML-KEM.Decaps is infallible: a tampered ciphertext decapsulates
//! to a pseudo-random shared secret derived from the implicit-
//! rejection secret `z` embedded in `dk`, not to an error. The
//! wrapper preserves that contract — [`MlKem768::decaps`] returns
//! `[u8; 32]` unconditionally on well-formed inputs. Callers MUST
//! wrap the shared secret in an authenticated transform (an AEAD
//! keyed by `K`, HMAC / KMAC over transcript, …) if they need to
//! detect a mismatch. See the RFC-8446-like handshake pattern R91
//! networking work uses.
//!
//! # Test vectors
//!
//! Three NIST ACVP known-answer vectors are embedded at the bottom
//! of this file and re-exported through [`crate::kem`]: one KeyGen
//! (`d, z -> ek, dk`), one Encaps (`ek, m -> c, K`), one Decaps
//! (`dk, c -> K`). Sources are cited beside each constant.

use alloc::string::String;

use ml_kem::{
    B32, Ciphertext, Encoded, EncapsulateDeterministic, EncodedSizeUser, KemCore,
    MlKem768 as MlKem768Core, array::Array, kem::Decapsulate,
};

use super::KemError;

/// Convenience alias — the RustCrypto ml-kem crate names the two
/// half-keys as associated types on `KemCore`. Naming them here
/// keeps the wrapper body legible when the type paths would
/// otherwise nest three levels deep.
type EncapKey = <MlKem768Core as KemCore>::EncapsulationKey;
/// See [`EncapKey`].
type DecapKey = <MlKem768Core as KemCore>::DecapsulationKey;

/// KeyGen seed length in bytes (`d` and `z` each, FIPS 203 §7.1).
pub const SEED_LEN: usize = 32;

/// Encapsulation-key length in bytes for ML-KEM-768 (FIPS 203 §7).
pub const EK_LEN: usize = 1184;

/// Decapsulation-key length in bytes for ML-KEM-768 (FIPS 203 §7).
pub const DK_LEN: usize = 2400;

/// Ciphertext length in bytes for ML-KEM-768 (FIPS 203 §7).
pub const CT_LEN: usize = 1088;

/// Shared-secret length in bytes (FIPS 203 §6 — all parameter sets).
pub const SS_LEN: usize = 32;

/// Static shape checks — a size drift in the underlying `ml-kem`
/// crate would silently disagree with the FFI thunks in
/// [`crate::ffi`]. Assert them at compile time so any regression
/// fails to build rather than fails at runtime.
const _: () = {
    // Sizes are dictated by `MlKem768Params: K=U3, Du=U10, Dv=U4` in
    // the `ml-kem` crate's `param.rs`:
    //   EncryptionKeySize    = 3 * 384 + 32       = 1184
    //   DecapsulationKeySize = 3 * 384 + 1184 + 32 + 32 = 2400
    //   CiphertextSize       = 3 * (10 * 32) + (4 * 32) = 1088
    // and the sizes above are the byte length equivalents.
    assert!(EK_LEN == 1184);
    assert!(DK_LEN == 2400);
    assert!(CT_LEN == 1088);
    assert!(SS_LEN == 32);
    assert!(SEED_LEN == 32);
};

/// ML-KEM-768 KEM marker type.
///
/// All operations are provided as associated functions; the struct
/// exists so downstream code can name the algorithm
/// (`MlKem768::keygen(...)`) without threading a generic parameter
/// through every call site. Mirrors the shape of [`crate::Argon2id`]
/// and [`crate::ChaCha20Poly1305`].
#[derive(Copy, Clone, Debug, Default)]
pub struct MlKem768;

impl MlKem768 {
    /// Deterministic KeyGen (FIPS 203 §7.1 / Algorithm 15).
    ///
    /// Given a 32-byte KeyGen seed `d` and a 32-byte implicit-
    /// rejection seed `z`, produce the encapsulation key `ek`
    /// (`EK_LEN` bytes) and the decapsulation key `dk` (`DK_LEN`
    /// bytes). `dk` bundles a private `d`-derived K-PKE decryption
    /// key, a copy of `ek` (as required by FIPS 203's `H(ek)`
    /// binding), the hash `H(ek)`, and the implicit-rejection secret
    /// `z`.
    ///
    /// # Determinism
    ///
    /// Byte-identical output across processes / CPUs for the same
    /// `(d, z)` — pinned by [`ACVP_KG_D`] / [`ACVP_KG_Z`] against
    /// [`ACVP_KG_EK`] / [`ACVP_KG_DK`] in this module's tests.
    ///
    /// # Errors
    ///
    /// Returns `Ok((ek, dk))` on well-formed inputs. The underlying
    /// crate's `generate_deterministic` cannot fail — the two seeds
    /// are fixed-size, and every intermediate rejection-sampling
    /// step is bounded — so this API is total for the current
    /// backend. The `Result` shape is preserved to keep the trait
    /// contract stable when a future paideia-native impl replaces
    /// the backend (a fallible rejection cap has been proposed for
    /// hardened deployments).
    pub fn keygen(
        seed_d: &[u8; SEED_LEN],
        seed_z: &[u8; SEED_LEN],
    ) -> Result<([u8; EK_LEN], [u8; DK_LEN]), KemError> {
        let d: B32 = Array(*seed_d);
        let z: B32 = Array(*seed_z);
        let (dk, ek) = MlKem768Core::generate_deterministic(&d, &z);
        let ek_bytes: Encoded<EncapKey> = ek.as_bytes();
        let dk_bytes: Encoded<DecapKey> = dk.as_bytes();
        let mut ek_out = [0u8; EK_LEN];
        let mut dk_out = [0u8; DK_LEN];
        ek_out.copy_from_slice(ek_bytes.as_slice());
        dk_out.copy_from_slice(dk_bytes.as_slice());
        Ok((ek_out, dk_out))
    }

    /// Deterministic Encaps (FIPS 203 §6.2 / Algorithm 16).
    ///
    /// Given an encapsulation key `ek` (`EK_LEN` bytes) and a
    /// 32-byte message-encoding seed `m`, produce the ciphertext
    /// `c` (`CT_LEN` bytes) and the shared secret `K` (`SS_LEN`
    /// bytes).
    ///
    /// # Determinism
    ///
    /// Byte-identical output across processes / CPUs for the same
    /// `(ek, m)` — pinned by [`ACVP_EN_EK`] / [`ACVP_EN_M`] against
    /// [`ACVP_EN_C`] / [`ACVP_EN_K`] in this module's tests.
    ///
    /// # Errors
    ///
    /// - [`KemError::Primitive`] if the underlying crate's
    ///   `encapsulate_deterministic` returns an error. It cannot
    ///   under FIPS 203 §6.2 (encapsulation is total on well-formed
    ///   inputs) but the crate's trait exposes a `Result<_, ()>`
    ///   shape we preserve rather than assume.
    pub fn encaps(
        ek_bytes: &[u8; EK_LEN],
        seed_m: &[u8; SEED_LEN],
    ) -> Result<([u8; CT_LEN], [u8; SS_LEN]), KemError> {
        // `EncodedSizeUser::from_bytes` takes a typed `Array<u8, N>`
        // reference. `Encoded<EncapKey>` resolves to `Array<u8,
        // U1184>` for the ML-KEM-768 parameter set; constructing it
        // from the caller's `[u8; 1184]` is a cheap 1184-byte copy
        // and the compiler validates the length at the type level.
        let ek_arr: Encoded<EncapKey> = Array(*ek_bytes);
        let ek = EncapKey::from_bytes(&ek_arr);
        let m: B32 = Array(*seed_m);
        let (c, k) = ek.encapsulate_deterministic(&m).map_err(|_| {
            KemError::Primitive(String::from(
                "ml-kem encapsulate_deterministic returned Err",
            ))
        })?;
        let mut c_out = [0u8; CT_LEN];
        let mut k_out = [0u8; SS_LEN];
        c_out.copy_from_slice(c.as_slice());
        k_out.copy_from_slice(k.as_slice());
        Ok((c_out, k_out))
    }

    /// Decaps (FIPS 203 §6.3 / Algorithm 17).
    ///
    /// Given a decapsulation key `dk` (`DK_LEN` bytes) and a
    /// ciphertext `c` (`CT_LEN` bytes), produce the shared secret
    /// `K` (`SS_LEN` bytes).
    ///
    /// # Implicit rejection
    ///
    /// The primitive is total. A tampered ciphertext yields the
    /// implicit-rejection fallback `J(z, c)` rather than an error —
    /// see the module-level "Implicit rejection" note. Callers that
    /// need to detect tampering wrap `K` in an authenticated
    /// transform (an AEAD keyed by `K` is the standard construction).
    ///
    /// # Errors
    ///
    /// - [`KemError::Primitive`] on an underlying-crate decoding
    ///   failure. The RustCrypto backend cannot currently reach
    ///   this branch for fixed-size inputs but the crate's public
    ///   `Result` shape is preserved.
    pub fn decaps(
        dk_bytes: &[u8; DK_LEN],
        ct_bytes: &[u8; CT_LEN],
    ) -> Result<[u8; SS_LEN], KemError> {
        let dk_arr: Encoded<DecapKey> = Array(*dk_bytes);
        let dk = DecapKey::from_bytes(&dk_arr);
        let ct_arr: Ciphertext<MlKem768Core> = Array(*ct_bytes);
        let k = dk.decapsulate(&ct_arr).map_err(|_| {
            KemError::Primitive(String::from("ml-kem decapsulate returned Err"))
        })?;
        let mut k_out = [0u8; SS_LEN];
        k_out.copy_from_slice(k.as_slice());
        Ok(k_out)
    }
}

